export const localizeProject = (project: Project, lang: "en" | "ar"): Project => {
  if (lang === "en") return project;
  const ar = projectsAr[project.slug];
  if (!ar) return project;
  return {
    ...project,
    title: ar.title,
    tagline: ar.tagline,
    overview: ar.overview,
    role: ar.role,
    duration: ar.duration,
    features: ar.features,
    metrics: project.metrics.map((m, i) => ({ ...m, label: ar.metricLabels[i] ?? m.label })),
  };
};

export const allProjectsAr = projects.map((p) => localizeProject(p, "ar"));
